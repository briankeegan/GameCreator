// THE FEATURE THAT CAN SEE A CHAIN THAT HAS NOT BEEN FIRED YET.
// Run: node chainpotential.test.js
//
// THE RULE, and it is PUYO_REFERENCE.md's, not ours: "greedy fires too
// early, and this is the real cap". A scorer that values the board NOW
// takes a chain the moment one exists, so potential never accumulates and
// long chains never happen. Its fix has two halves — a patience term, and
// "an evaluation that scores the biggest chain I COULD fire rather than the
// biggest chain available now". This is that second half.
//
// WHY IT IS MISSING AND WHY THAT MATTERS. Every feature here reads the
// board as it stands or a cascade already running: chainLength scores a
// chain being fired, latentChain scores one in flight. Nothing scores
// STORED potential, so "I am sitting on a loaded 5-chain and choosing not
// to trigger it" is not a state the evaluator can represent. Measured
// consequence: a trained set weighting chainLength at 278 — its largest
// weight — produced 0% medium chains on three of four drills. The weight
// could not express the thing, so the search could not find it.
//
// WHAT IT MEASURES: over every legal swap on the SETTLED board, the
// deepest cascade any one of them would set off. Not the swap being
// considered — the board's readiness, which is what a patient player is
// building and what an impatient one spends.
var assert = require('assert');
var path = require('path');
require(path.join(__dirname, '..', '..', 'panel-engine.js'));
require(path.join(__dirname, '..', '..', 'panel-cpu.js'));
var PanelCpu = globalThis.PanelCpu;
var features = require('./features.js');

var tests = [], failures = [];
function test(name, fn) { tests.push({ name: name, fn: fn }); }

// Text rows, top first, into a REAL LogicalBoard — the same class the cpu
// plans against — so gravity, matching and garbage behave exactly as they
// do in the game rather than as a second implementation in this file.
function board(rows, colours) {
    var height = rows.length, width = rows[0].length, grid = [], r, c;
    for (r = 0; r <= height; r++) grid[r] = [];
    for (r = 0; r < height; r++) {
        var line = rows[r], row = height - r;
        assert.strictEqual(line.length, width, 'row ' + r + ' is a different width');
        for (c = 1; c <= width; c++) {
            var ch = line[c - 1];
            grid[row][c] = ch === '.' ? 0 : ch === 'x' ? -1 : ch === '#' ? -2 : Number(ch);
            assert.ok(!isNaN(grid[row][c]), 'bad cell "' + ch + '"');
        }
    }
    var blocks = {}, seen = {}, next = 1;
    for (r = 1; r <= height; r++) for (c = 1; c <= width; c++) {
        if (grid[r][c] !== -2 || seen[r + ':' + c]) continue;
        var id = 'g' + (next++), cells = [], stack = [[r, c]];
        while (stack.length) {
            var n = stack.pop(), k = n[0] + ':' + n[1];
            if (seen[k] || grid[n[0]] === undefined || grid[n[0]][n[1]] !== -2) continue;
            seen[k] = true; cells.push(n);
            stack.push([n[0] + 1, n[1]], [n[0] - 1, n[1]], [n[0], n[1] + 1], [n[0], n[1] - 1]);
        }
        blocks[id] = { cells: cells };
    }
    return new PanelCpu.LogicalBoard(width, height, colours || 5, grid, blocks);
}

function chainPotential(b) { return features.chainPotential({ board: b }); }

// The independent answer: actually play every legal swap and see. Slow,
// obviously correct, and NOT the implementation — a feature checked only
// against its own logic is checked against nothing.
function bruteForce(b) {
    var best = 0;
    var swaps = b.legalSwaps();
    for (var i = 0; i < swaps.length; i++) {
        var t = b.clone();
        t.swap(swaps[i][0], swaps[i][1]);
        var r = t.resolve();
        if (r.chainLength > best) best = r.chainLength;
    }
    return best;
}

// FIXTURES FOUND BY SEARCH, NOT DRAWN BY EYE. The first three attempts at
// hand-drawing a "loaded 3-chain" all held a 1-chain, and one "no chain
// available" board offered a pop — which would have made the tests pass
// against a feature that simply returned 1. Each of these was generated by
// settling random boards until one brute-forced to the exact depth wanted.
var DEPTH_0 = [
    '......',
    '......',
    '......',
    '......',
    '31...2',
    '231.23'
];
var DEPTH_1 = [
    '......',
    '...3..',
    '.1.2..',
    '32.2..',
    '22.1.1',
    '132331'
];
var DEPTH_2 = [
    '......',
    '......',
    '31....',
    '213...',
    '1233.2',
    '1311.1'
];
var DEPTH_3 = [
    '......',
    '......',
    '.....1',
    '1.1..2',
    '2121.3',
    '2233.3'
];

test('a board with nothing to fire scores zero', function () {
    var b = board(DEPTH_0);
    assert.strictEqual(bruteForce(b), 0, 'the board itself must have no chain available');
    assert.strictEqual(chainPotential(b), 0);
});

test('a one-swap match with no cascade scores 1', function () {
    var b = board(DEPTH_1);
    assert.strictEqual(bruteForce(b), 1, 'this board should offer a single pop');
    assert.strictEqual(chainPotential(b), 1);
});

test('a loaded chain scores its FULL depth, unfired', function () {
    // The point of the whole feature: the board has not chained, chainLength
    // on it is 0, and this must still see what is stored there.
    var b = board(DEPTH_3);
    var depth = bruteForce(b);
    assert.strictEqual(depth, 3, 'the fixture must hold a 3-chain, got ' + depth);
    assert.strictEqual(chainPotential(b), depth);
    // And the contrast that justifies the feature existing at all:
    // And the contrast that justifies the feature existing at all: on this
    // same board, the feature that supposedly covers chains sees nothing,
    // because the chain has not been fired. That gap is the whole point.
    assert.strictEqual(features.chainLength({ earned: { chainLength: 0 } }), 0,
        'a settled board has fired nothing, so chainLength scores 0 on it — ' +
        'while chainPotential scores ' + chainPotential(b));
});

test('a deeper board scores higher than a shallower one', function () {
    var loaded = board(DEPTH_3), broken = board(DEPTH_1);
    assert.ok(chainPotential(loaded) > chainPotential(broken),
        'depth-3 board scored ' + chainPotential(loaded) + ', depth-1 board ' +
        chainPotential(broken) + '. If these are equal the feature is not ' +
        'measuring chain depth, it is measuring something that correlates with ' +
        'it on one board.');
});

test('it does not mutate the board it is given', function () {
    // matchPotential swaps cells and swaps them back; a bug of that shape
    // here corrupts the board the search is ranking, silently, for every
    // candidate after it.
    var b = board(DEPTH_3);
    var before = JSON.stringify(b.grid);
    chainPotential(b);
    assert.strictEqual(JSON.stringify(b.grid), before, 'the grid came back changed');
});

test('it agrees with brute force on many random boards', function () {
    // One hand-made fixture proves the happy path and nothing else. Random
    // boards are where an off-by-one in the swap loop or a missed column
    // shows up — and the failures are COLLECTED so one run answers "which
    // boards?" rather than "the first board".
    var rngState = 20260908;
    function rng() { rngState = (rngState * 1103515245 + 12345) & 0x7fffffff; return rngState / 0x7fffffff; }
    var wrong = [], nonZero = 0, seen = {};
    for (var n = 0; n < 120; n++) {
        var rows = [], H = 6, W = 6;
        for (var r = 0; r < H; r++) {
            var line = '';
            for (var c = 0; c < W; c++) {
                // Denser at the bottom, like a real stack, and sparse enough
                // up top that gravity actually has somewhere to drop things.
                var fill = (r + 1) / (H + 1);
                line += rng() < fill ? String(1 + Math.floor(rng() * 4)) : '.';
            }
            rows.push(line);
        }
        var b = board(rows);
        var settled = b.clone();
        settled.resolve();               // start from a SETTLED board, which is
        var grid = settled.grid;         // the only kind this feature is defined on
        var b2 = board(grid.slice(1).map(function (row) {
            return row.slice(1).map(function (v) {
                return v === 0 ? '.' : v === -1 ? 'x' : v === -2 ? '#' : String(v);
            }).join('');
        }).reverse());
        var expect = bruteForce(b2), got = chainPotential(b2);
        if (expect > 0) nonZero++;
        seen[expect] = (seen[expect] || 0) + 1;
        if (expect !== got) wrong.push('board ' + n + ': brute force ' + expect + ', feature ' + got);
    }
    assert.ok(nonZero >= 20,
        'only ' + nonZero + ' of 120 random boards had any chain available — the ' +
        'sample is too tame to be testing anything. Distribution: ' + JSON.stringify(seen));
    assert.ok(Object.keys(seen).length >= 3,
        'only ' + Object.keys(seen).length + ' distinct depths seen (' + JSON.stringify(seen) +
        '); a feature can be wrong about deep chains and right about shallow ones.');
    assert.deepStrictEqual(wrong.slice(0, 10), [],
        wrong.length + ' boards disagreed with brute force:\n  ' + wrong.slice(0, 10).join('\n  '));
});

// ---------------------------------------------------- comboPotential
//
// THE OTHER HALF OF STORED POTENTIAL, tested here rather than in
// features.test.js because — like chainPotential — it has to be asked of a
// REAL LogicalBoard: it clones, swaps and resolves, and a hand-built plain
// object has none of those.
//
// chainPotential measures how DEEP a cascade could go. matchPotential counts
// HOW MANY swaps pay out and says in its own comment that size belongs in
// its own feature. This measures how BIG the biggest single clear could be.
function comboPotential(b) { return features.comboPotential({ board: b }); }

// Independent answer, written from the definition rather than from the
// implementation: every legal swap, resolved by the engine, biggest combo
// size reported. Deliberately not shared with the feature's code.
function bruteCombo(b) {
    var swaps = b.legalSwaps(), best = 0, i, j;
    for (i = 0; i < swaps.length; i++) {
        var t = b.clone();
        t.swap(swaps[i][0], swaps[i][1]);
        var sizes = t.resolve().comboSizes || [];
        for (j = 0; j < sizes.length; j++) if (sizes[j] > best) best = sizes[j];
    }
    return best;
}

// A settled random board, built the same way the chainPotential random test
// builds one — resolve first, because both features are defined only on a
// board with nothing in flight.
function randomSettled(seed) {
    var rngState = seed;
    function rng() { rngState = (rngState * 1103515245 + 12345) & 0x7fffffff; return rngState / 0x7fffffff; }
    var rows = [], H = 6, W = 6, r, c;
    for (r = 0; r < H; r++) {
        var line = '';
        for (c = 0; c < W; c++) {
            var fill = (r + 1) / (H + 1);
            line += rng() < fill ? String(1 + Math.floor(rng() * 4)) : '.';
        }
        rows.push(line);
    }
    var settled = board(rows).clone();
    settled.resolve();
    var grid = settled.grid;
    return board(grid.slice(1).map(function (row) {
        return row.slice(1).map(function (v) {
            return v === 0 ? '.' : v === -1 ? 'x' : v === -2 ? '#' : String(v);
        }).join('');
    }).reverse());
}

test('comboPotential: an empty board offers no clear at all', function () {
    assert.strictEqual(comboPotential(board(DEPTH_0)), 0);
});

test('comboPotential: FIRES on a reachable clear and reports its SIZE, not a count', function () {
    // 1,1,.,1 across the floor: one swap brings the fourth 1 in and the
    // engine clears four. A feature that counted paying swaps rather than
    // measuring size cannot tell this from a bare three.
    var four = board(['......', '......', '......', '......', '11.1..']);
    var three = board(['......', '......', '......', '......', '1.1...']);
    assert.strictEqual(comboPotential(four), bruteCombo(four), 'must agree with brute force');
    assert.ok(comboPotential(four) > comboPotential(three),
        'the four-panel clear must outscore the three (' + comboPotential(four) + ' vs ' +
        comboPotential(three) + ')');
});

test('comboPotential: SIZE is what separates it from matchPotential', function () {
    // matchPotential counts swaps that pay out; if this scored these two the
    // same it would be a duplicate of a feature that already exists.
    var small = board(['......', '......', '......', '......', '11.1..']);
    var big = board(['......', '......', '......', '......', '111.11']);
    assert.ok(comboPotential(big) > comboPotential(small),
        'the wider clear must score higher (' + comboPotential(big) + ' vs ' +
        comboPotential(small) + ')');
});

test('comboPotential: it is the MAX, not the sum over swaps', function () {
    // Payout is per-clear, so one clear of six beats two of three, and a sum
    // over every legal swap would be far larger than any single clear.
    var b = board(['......', '......', '......', '......', '111.11']);
    assert.strictEqual(comboPotential(b), bruteCombo(b));
    assert.ok(comboPotential(b) <= 6 * 6, 'cannot exceed the board width times its height');
    assert.ok(comboPotential(b) < 12, 'a sum over swaps would be far larger than any one clear');
});

test('comboPotential: agrees with brute force over random settled boards', function () {
    // The same cross-check chainPotential gets, and for the same reason: a
    // feature checked only against its own logic is checked against nothing.
    var wrong = [], seen = {}, i;
    for (i = 0; i < 120; i++) {
        var b = randomSettled(20260908 + i);
        var got = comboPotential(b), want = bruteCombo(b);
        seen[want] = (seen[want] || 0) + 1;
        if (got !== want) wrong.push('seed ' + i + ': got ' + got + ' want ' + want);
    }
    assert.ok(Object.keys(seen).length >= 2,
        'only one distinct size seen (' + JSON.stringify(seen) + '), so this proves nothing');
    assert.deepStrictEqual(wrong.slice(0, 10), [], wrong.length + ' boards disagreed:\n  ' +
        wrong.slice(0, 10).join('\n  '));
});

tests.forEach(function (t) {
    try { t.fn(); console.log('ok   ' + t.name); }
    catch (e) { failures.push(t.name); console.log('FAIL ' + t.name + '\n     ' + e.message); }
});
console.log('\n' + (tests.length - failures.length) + '/' + tests.length + ' passed');
process.exit(failures.length ? 1 : 0);
